#ifndef _MUPTYPES_H
#define _MUPTYPES_H

//
// Dependencies
//
#include <umtypes.h>

//
// FSCTL sent to MUP for UNC provider registration
//
#define FSCTL_MUP_REGISTER_PROVIDER CTL_CODE(FILE_DEVICE_MULTI_UNC_PROVIDER, 1, METHOD_BUFFERED, FILE_ANY_ACCESS)

//
// Input buffer for FSCTL_MUP_REGISTER_PROVIDER
//
typedef struct _MUP_PROVIDER_REGISTRATION_INFO
{
    ULONG RedirectorDeviceNameOffset;
    ULONG RedirectorDeviceNameLength;
    ULONG Reserved[2];
    BOOLEAN MailslotsSupported;
} MUP_PROVIDER_REGISTRATION_INFO, *PMUP_PROVIDER_REGISTRATION_INFO;

typedef struct _MUP_PROVIDER_REGISTRATION_INFO_PRIVATE
{
    MUP_PROVIDER_REGISTRATION_INFO Public;
    PVOID DeviceObject;
} MUP_PROVIDER_REGISTRATION_INFO_PRIVATE, *PMUP_PROVIDER_REGISTRATION_INFO_PRIVATE;

C_ASSERT(FIELD_OFFSET(MUP_PROVIDER_REGISTRATION_INFO_PRIVATE, Public) == 0);
C_ASSERT(FIELD_OFFSET(MUP_PROVIDER_REGISTRATION_INFO_PRIVATE, DeviceObject) >=
         sizeof(MUP_PROVIDER_REGISTRATION_INFO));

#endif // _MUPTYPES_H
